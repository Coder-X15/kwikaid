-- One-time setup for KwikAid. Paste into Supabase -> SQL Editor and run.
-- Safe to re-run.

-- 1. Queue of photos waiting for the CV model --------------------------------
create table if not exists public.inference_queue (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid references auth.users (id) on delete cascade default auth.uid(),
  status       text not null default 'queued'
                 check (status in ('queued', 'processing', 'completed', 'failed')),
  inference    text default 'incomplete',
  storage_path text not null,
  storage_url  text not null,   -- link to the object in the Supabase bucket
  created_at   timestamptz not null default now()
);

create index if not exists inference_queue_status_idx
  on public.inference_queue (created_at)
  where status = 'queued';

-- 2. Row-level security: users only see and add their own rows. -------------
-- The worker uses the service_role key, which bypasses RLS.
alter table public.inference_queue enable row level security;

drop policy if exists "Users queue their own photos" on public.inference_queue;
create policy "Users queue their own photos" on public.inference_queue
  for insert to authenticated
  with check (user_id = (select auth.uid()));

drop policy if exists "Users read their own results" on public.inference_queue;
create policy "Users read their own results" on public.inference_queue
  for select to authenticated
  using (user_id = (select auth.uid()));

-- 3. Private bucket for injury photos, one folder per user (<user_id>/...) ---
insert into storage.buckets (id, name, public)
values ('injury-images', 'injury-images', false)
on conflict (id) do nothing;

drop policy if exists "Users upload to their own folder" on storage.objects;
create policy "Users upload to their own folder" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'injury-images' and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "Users read their own photos" on storage.objects;
create policy "Users read their own photos" on storage.objects
  for select to authenticated
  using (bucket_id = 'injury-images' and (storage.foldername(name))[1] = (select auth.uid())::text);

-- 4. Incident log: one row per assessment, private to its user --------------
create table if not exists public.incidents (
  id          text primary key,   -- INC-xxxx, generated by the app
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  created_at  timestamptz not null default now(),
  injury_type text not null,
  label       text not null,
  severity    text not null check (severity in ('minor', 'moderate', 'severe')),
  symptoms    text[] not null default '{}',
  photo_name  text,
  steps_total int not null,
  steps_done  int not null default 0,
  call_placed boolean not null default false,
  call_number text,
  notes       text[] not null default '{}'
);

create index if not exists incidents_user_created_idx
  on public.incidents (user_id, created_at desc);

alter table public.incidents enable row level security;

drop policy if exists "Users read their own incidents" on public.incidents;
create policy "Users read their own incidents" on public.incidents
  for select to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "Users log their own incidents" on public.incidents;
create policy "Users log their own incidents" on public.incidents
  for insert to authenticated
  with check (user_id = (select auth.uid()));

drop policy if exists "Users update their own incidents" on public.incidents;
create policy "Users update their own incidents" on public.incidents
  for update to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));
